#!/usr/bin/env node
/**
 * Merge missing locale keys from en.json, using per-locale patch translations when available.
 * Every English placeholder left in a locale is recorded in lib/i18n/translation-status.json
 * (locale → key → { status: "needs_translation", en_hash }) so the audit can tell it apart
 * from a real translation. See docs/I18N.md.
 * Usage: node scripts/sync-i18n-keys.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import coverage from "./lib/i18nCoverage.js";

const { syncLocale, sortObject, serializeStatus } = coverage;

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const i18nDir = path.join(__dirname, "..", "lib", "i18n");
const localesDir = path.join(i18nDir, "locales");
const patchesDir = path.join(i18nDir, "patches");
const statusPath = path.join(i18nDir, "translation-status.json");
const config = JSON.parse(fs.readFileSync(path.join(i18nDir, "coverage-config.json"), "utf8"));

const STATUS_README =
  "Generated by `npm run sync-i18n` — do not edit by hand. Each entry is an English placeholder " +
  "(en_hash = hash of the English copied in). Translating the value removes it on the next sync. See docs/I18N.md.";

const en = JSON.parse(fs.readFileSync(path.join(localesDir, "en.json"), "utf8"));

/** Merge all patch files in lib/i18n/patches/ (locale → key → translation). */
function loadMergedPatches() {
  const merged = {};
  if (!fs.existsSync(patchesDir)) return merged;
  for (const file of fs.readdirSync(patchesDir).filter((f) => f.endsWith(".json"))) {
    const data = JSON.parse(fs.readFileSync(path.join(patchesDir, file), "utf8"));
    for (const [locale, keys] of Object.entries(data)) {
      merged[locale] = { ...(merged[locale] ?? {}), ...keys };
    }
  }
  return merged;
}

const patches = loadMergedPatches();
const prevStatus = fs.existsSync(statusPath) ? JSON.parse(fs.readFileSync(statusPath, "utf8")) : {};
const nextStatus = {};

const files = fs
  .readdirSync(localesDir)
  .filter((f) => f.endsWith(".json") && f !== "en.json" && !f.startsWith("_"));

let updated = 0;
for (const file of files.sort()) {
  const locale = file.replace(".json", "");
  const filePath = path.join(localesDir, file);
  const loc = JSON.parse(fs.readFileSync(filePath, "utf8"));

  const result = syncLocale({
    en,
    loc,
    locale,
    patch: patches[locale] ?? {},
    allowlist: config.allowlist,
    status: prevStatus[locale] ?? {},
  });
  nextStatus[locale] = result.status;

  if (result.added.length || result.refreshed.length) {
    fs.writeFileSync(filePath, `${JSON.stringify(sortObject(result.loc), null, 2)}\n`, "utf8");
    updated += 1;
    const parts = [];
    if (result.added.length) parts.push(`${result.added.length} added`);
    if (result.refreshed.length) parts.push(`${result.refreshed.length} placeholder(s) refreshed to new English`);
    console.log(`Updated ${file}: ${parts.join(", ")}`);
  }
}

const serialized = serializeStatus(nextStatus, STATUS_README);
const statusChanged = !fs.existsSync(statusPath) || fs.readFileSync(statusPath, "utf8") !== serialized;
if (statusChanged) fs.writeFileSync(statusPath, serialized, "utf8");

const pending = Object.values(nextStatus).reduce((n, s) => n + Object.keys(s).length, 0);
console.log(updated ? `\nSynced ${updated} locale file(s).` : "\nAll locales already up to date.");
console.log(`${pending} placeholder(s) need translation (lib/i18n/translation-status.json${statusChanged ? ", updated" : ""}).`);
